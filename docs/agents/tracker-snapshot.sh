#!/usr/bin/env bash
# Regenerate docs/agents/tracker-snapshot.md from the GitHub issue tracker.
# The tracker (GitHub issues) is the canonical artifact; this snapshot is a
# readable backup of the wayfinder map and its tickets committed to git.
# Run from anywhere inside the repo: ./docs/agents/tracker-snapshot.sh
set -euo pipefail

MAP=1
REPO=LiveSparks/open-webui
export GH_REPO="$REPO"
OUT="$(dirname "$0")/tracker-snapshot.md"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo "# Wayfinder tracker snapshot"
  echo
  echo "> Generated by \`docs/agents/tracker-snapshot.sh\` from GitHub issues."
  echo "> The canonical copy lives on the issue tracker; update this file and"
  echo "> commit after any map or ticket change. Never edit by hand."
  echo

  echo "## Map #$MAP"
  echo
  gh issue view "$MAP" --json body --jq .body
  echo

  echo "## Tickets"
  echo
  gh api "repos/{owner}/{repo}/issues/$MAP/sub_issues" \
    --paginate --jq 'sort_by(.number) | reverse | .[] | select(.number != '"$MAP"') | "\(.state)|\(.title)|\(.number)|\([.assignees[].login] | join(","))|\([.labels[].name] | join(","))"' |
    while IFS='|' read -r state title number assignees labels; do
      tmp2="$(mktemp)"
      gh issue view "$number" --json body --jq .body >"$tmp2"
      {
        echo "### $state #$number — $title"
        echo
        echo "[Open on GitHub](https://github.com/{owner}/{repo}/issues/$number) \`$labels\` assignees: ${assignees:-none}"
        echo
        cat "$tmp2"
        echo
      } >>"$tmp"
      rm -f "$tmp2"
    done

  cat "$tmp"
} > "$OUT"

echo "wrote $OUT ($(wc -l <"$OUT") lines)"
